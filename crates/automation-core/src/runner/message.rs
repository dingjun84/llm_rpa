//! **准备消息**：聚焦输入框 → 记下发送前基线 → 把正文逐字填进去 → 发送。
//!
//! ## 发送动作由什么组成
//!
//! 「逐字输入正文 + 点发送按钮」，两样都是（2026-09-22 操作者指定）。
//!
//! - **不粘贴**：粘贴要过剪贴板，一来会覆盖操作者自己的剪贴板内容，
//!   二来它在客户端那边是"一次到达"的，中间没有任何可核对的痕迹。
//!   逐字输入与搜索框那条路共用同一个端口，就不存在"某一条输入路径从没被验证过"。
//! - **不按快捷键**：客户的发送键设置（Enter / ⌘+Enter）是**因人而异**的，
//!   按错键的表现是"输入框里多了一个换行、消息没出去"，看起来像发送失败。
//!   点按钮不依赖任何键盘设置。
//!
//! ## 「发还是不发」由谁保证
//!
//! 判据**只有一条**：配置里的「只填不发」（`stop_before_send`）。
//! 勾了就停在 [`TaskState::Prepared`]，没勾就**直接发出去**——
//! 与走的是哪条工作流无关。
//!
//! ⚠️ 不要把这条判据再摊开成"某条工作流特殊"：曾经搜索式无条件停在这里
//! （`docs/todo.md` T16 的临时取舍），现在它和列表扫描式同路。
//! 两条路**各写一套**"发不发"的判断，迟早会出现「界面上勾了什么、实际按哪条算」
//! 说不清，而这恰好是最不能说不清的一件事。
//!
//! ⚠️ 「只填不发」那条分支**不能走到发送**：它存在的全部意义就是"绝不发送"，
//! 所以既不申请发送台账、也不写消息摘要——审计里不该留下任何"像发过了"的痕迹。
//!
//! ## 为什么没有"人工确认"这一步了
//!
//! 2026-09-22 移除（操作者要求）。原来在发送前会阻塞等操作者在界面上点一次
//! "确认发送"，理由是"发送不可撤销"。实际用下来它挡不住真正要挡的东西：
//!
//! - **它挡不住"发错人"**：确认框里显示的是姓名和正文，而操作者刚在任务表单里
//!   填过同样两样东西，看一眼即点。真正会出错的地方（下拉里选中的是哪一行、
//!   聊天标题是不是那个人）在框里看不到。
//! - **它把一次卡顿变成一次失败**：确认有有效期（60 秒），操作者正好不在电脑前
//!   就是 `NeedsHumanReview`（`data/tasks/da89a816-…` 的现场：任务一路跑到
//!   `PreparingMessage`，卡了整整 60 秒，然后以"人工确认已过期"结束，
//!   消息始终没发出去）。
//!
//! 所以"发不发"这件事改由**运行前的一个显式选择**决定：勾「只填不发」= 只看不发，
//! 不勾 = 发。剩下的边界仍然是硬的：任务级幂等台账（同一任务不可能发两次）、
//! 发送后的送达核验、以及演练模式下整组端口是替身。
//!
//! ⚠️ 代价要说清：**"找错人"现在没有任何自动闸门**。误发的防线只剩两道——
//! 运行前的「只填不发」试跑，以及日志里那条"放宽匹配 + 允许真实发送"的警告。
//!
//! ## 演练模式为什么不在这里提前停
//!
//! 演练模式下端口整组都是替身（`platform-mock`），`send` 只在本进程里记一笔，
//! 碰不到任何真实窗口。所以"不会真的发出去"**由替身端口保证**，
//! 不靠在这里提前停——否则演练模式下流程会缺掉后半截，
//! 而人拿它当"流程验证"的时候并不知道少了什么。
//!
//! ## 真实模式下的顺序
//!
//! 不勾「只填不发」⇒ claim 发送台账 → 写消息摘要 → 进 [`TaskState::Sending`]
//! → 逐字输入 → 点发送按钮 → 核验送达。中间没有第二个等待点。
//!
//! ## 2026-10 清理
//!
//! 本文件已不再编入任何活代码路径：YOLO 工作流的输入 / 发送 / 送达核验在
//! `yolo_send_verify.rs`，送达判据（**画面变了且读得到正文**，与原 `verify_delivery`
//! 同口径）收敛为 `yolo_verify_rules::judge_delivery`。原 `prepare_message`、
//! `type_into_composer`、`send_and_verify`、`click_send_button`、`verify_delivery`
//! 与重复的 `resolve_extra` 已删除（无任何引用）。文件按操作者决定保留，不删；
//! 上面的设计说明（不粘贴、不按快捷键、`stop_before_send` 唯一判据）对新实现同样成立。
