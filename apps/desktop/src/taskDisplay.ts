/**
 * 任务在界面上怎么显示那几个字段。
 *
 * 只有一条规则，但它必须**只写一处**：任务列表和「当前任务」两处都显示收件人，
 * 两处各写一句 fallback 的话，改文案时必然漏掉一处。
 */

/**
 * 「收件人」这一栏显示什么。
 *
 * ★ 空名字**不是"漏填了"**：「只做导航」那条工作流根本不查找任何人
 * （见 `Workflow::NavigateOnly`），任务请求里那个联系人字段就是空的，
 * 命令层也不再拿它当必填。空着显示会让人以为界面上少读了什么，
 * 或者以为操作者忘了填——所以给它一句实话。
 */
export function contactLabel(name: string): string {
  return name.trim() === "" ? "（这条工作流不找人）" : name;
}
